import argparse
import base64
import json
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from urllib.parse import urlsplit
from xml.sax.saxutils import escape


ROOT = Path(__file__).resolve().parent


def replace(path, pattern, replacement):
    path = ROOT / path
    original = path.read_text(encoding="utf-8")
    lines, count = re.subn(pattern, lambda _: replacement, original, flags=re.M)
    if count != 1:
        raise ValueError(f"{path}: expected one match for {pattern}, got {count}")
    if lines != original:
        path.write_text(lines, encoding="utf-8")


def quote(value):
    return json.dumps(value, ensure_ascii=False)


def apply(config, api_override):
    name = config["app_name"]
    package = config["package_id"]
    color = config["primary_color"]
    api = (api_override or config["license_api_base_url"]).rstrip("/")
    parts = urlsplit(api)
    if (parts.scheme != "https" and
            (parts.scheme != "http" or parts.hostname not in {"127.0.0.1", "localhost"})):
        raise ValueError("License API must use HTTPS, except for a localhost mock")
    if not parts.hostname or parts.username or parts.password or parts.query or parts.fragment:
        raise ValueError("Invalid license API base URL")
    if not re.fullmatch(r"[\w. ()\[\]-]+", name) or not re.search(r"\w", name):
        raise ValueError("Invalid app name")
    # Tên hiển thị cho người dùng (25/11/2026: "Mecha Remote"). app_name giữ "Mecha" cho định danh nội bộ
    # (APP_NAME: thư mục cấu hình, tên dịch vụ, ống IPC) để không có dấu cách trong đường dẫn và tên dịch vụ.
    display = config.get("display_name") or name
    if not re.fullmatch(r"[\w. ()\[\]-]+", display) or not re.search(r"\w", display):
        raise ValueError("Invalid display name")
    if not re.fullmatch(r"[a-z][a-z0-9_]*(?:\.[a-z][a-z0-9_]*)+", package):
        raise ValueError("Invalid Android application ID")
    if not re.fullmatch(r"#[0-9a-fA-F]{6}", color):
        raise ValueError("Invalid primary color")
    if len(base64.b64decode(config["server_public_key"], validate=True)) != 32:
        raise ValueError("Expected a 32-byte base64-encoded server public key")
    source_url = config["source_url"]
    if source_url and not source_url.startswith("https://"):
        raise ValueError("Source URL must use HTTPS")
    magick = shutil.which("magick") or shutil.which("convert")
    if not magick:
        raise RuntimeError("Install ImageMagick first")
    svg = (ROOT / config["logo_svg"]).read_text(encoding="utf-8").replace(
        "{{PRIMARY_COLOR}}", color
    )
    dart = ROOT / "flutter/lib/common/brand.dart"
    dart.write_text(
        "// Generated by apply-branding.py. Edit branding.json instead.\n"
        f"const brandName = {quote(display)};\n"
        f"const brandRgb = 0x{color[1:]};\n"
        f"const brandLicenseApi = {quote(api).replace(chr(36), chr(92) + chr(36))};\n"
        f"const brandSourceUrl = {quote(source_url).replace(chr(36), chr(92) + chr(36))};\n"
        f"const brandShowServerSettings = {str(config['show_server_settings']).lower()};\n"
        f"const brandFreeAddressBookMax = {int(config['plans']['free']['address_book_max'])};\n",
        encoding="utf-8",
    )
    conf = "libs/hbb_common/src/config.rs"
    replace(conf, r'^    pub static ref APP_NAME:.*;$',
            f"    pub static ref APP_NAME: RwLock<String> = RwLock::new({quote(name)}.to_owned());")
    replace(conf, r'^pub const RENDEZVOUS_SERVERS:.*;$',
            f"pub const RENDEZVOUS_SERVERS: &[&str] = &[{quote(config['rendezvous'])}];")
    replace(conf, r'^    pub static ref PROD_RENDEZVOUS_SERVER:.*;$',
            f"    pub static ref PROD_RENDEZVOUS_SERVER: RwLock<String> = RwLock::new({quote(config['rendezvous'])}.to_owned());")
    replace(conf, r'^pub const RS_PUB_KEY:.*;$',
            f"pub const RS_PUB_KEY: &str = {quote(config['server_public_key'])};")
    replace(conf, r'^    pub static ref DEFAULT_SETTINGS:.*;$',
            '    pub static ref DEFAULT_SETTINGS: RwLock<HashMap<String, String>> = '
            f'RwLock::new(HashMap::from([("relay-server".to_owned(), {quote(config["relay"])}.to_owned())]));')
    replace(conf, r'(?s)    fn get_auto_id\(\) -> Option<String> \{.*?\n    \}',
            "    fn get_auto_id() -> Option<String> {\n"
            "        Some(rand::thread_rng().gen_range(100_000_000..1_000_000_000).to_string())\n"
            "    }")
    replace("flutter/android/app/build.gradle", r'^        applicationId ".*"$',
            f'        applicationId "{package}"')
    android = "flutter/android/app/src/main"
    replace(f"{android}/AndroidManifest.xml", r'android:scheme="[^"]+"',
            f'android:scheme="{package}"')
    replace(f"{android}/res/values/strings.xml", r'<string name="app_name">.*</string>',
            f'<string name="app_name">{escape(display)}</string>')
    replace(f"{android}/res/values/ic_launcher_background.xml",
            r'<color name="ic_launcher_background">.*</color>',
            f'<color name="ic_launcher_background">{color}</color>')
    replace(f"{android}/res/values/colors.xml",
            r'<color name="primary">.*</color>',
            f'<color name="primary">#FF{color[1:]}</color>')
    replace("Cargo.toml", r'^description = "[^"]+"$',
            f'description = {quote(display + " - Điều khiển từ xa")}')
    replace("Cargo.toml", r'^ProductName = "[^"]+"$', f"ProductName = {quote(display)}")
    replace("Cargo.toml", r'^FileDescription = "[^"]+"$', f"FileDescription = {quote(display)}")
    replace("Cargo.toml", r'^\[package.metadata.bundle\]\nname = "[^"]+"$',
            f"[package.metadata.bundle]\nname = {quote(display)}")
    replace("Cargo.toml", r'^identifier = "[^"]+"$', f"identifier = {quote(package)}")
    replace("flutter/pubspec.yaml", r'^description: .+$',
            f"description: {quote(display + ' - Điều khiển từ xa')}")
    rc = "flutter/windows/runner/Runner.rc"
    for field in ("ProductName", "FileDescription"):
        replace(rc, rf'VALUE "{field}", ".*" "\\0"', f'VALUE "{field}", {quote(display)} "\\0"')
    replace("flutter/windows/runner/main.cpp", r'std::wstring app_name = L"[^"]+";',
            f'std::wstring app_name = L{quote(name)};')
    replace("flutter/linux/my_application.cc", r'gtk_header_bar_set_title\(header_bar, "[^"]+"\);',
            f'gtk_header_bar_set_title(header_bar, {quote(display)});')
    replace("flutter/linux/my_application.cc", r'gtk_window_set_title\(window, "[^"]+"\);',
            f'gtk_window_set_title(window, {quote(display)});')
    replace("flutter/linux/CMakeLists.txt", r'^set\(APPLICATION_ID "[^"]+"\)$',
            f'set(APPLICATION_ID "{package}")')
    replace("src/common.rs", r'^pub\(crate\) const BRAND_URI_SCHEME: &str = "[^"]+";$',
            f"pub(crate) const BRAND_URI_SCHEME: &str = {quote(package)};")

    (ROOT / "flutter/assets/icon.svg").write_text(svg, encoding="utf-8")
    (ROOT / "res/logo.svg").write_text(svg, encoding="utf-8")
    (ROOT / "res/scalable.svg").write_text(svg, encoding="utf-8")
    source = ROOT / config["icon_png"]
    with tempfile.TemporaryDirectory() as temp:
        def render(path, size):
            subprocess.run([magick, "-background", "none", str(source), "-resize",
                            f"{size}x{size}", "-strip", f"PNG32:{ROOT / path}"], check=True)

        for path in ("flutter/assets/icon.png", "res/icon.png", "res/128x128@2x.png"):
            render(path, 256)
        for key, asset in (("logo_light_svg", "logo.png"),
                           ("logo_dark_svg", "logo_dark.png")):
            subprocess.run([magick, "-background", "none", str(ROOT / config[key]),
                            "-strip", f"PNG32:{ROOT / 'flutter/assets' / asset}"], check=True)
        for dpi, size in zip(("mdpi", "hdpi", "xhdpi", "xxhdpi", "xxxhdpi"), (48, 72, 96, 144, 192)):
            folder = f"{android}/res/mipmap-{dpi}"
            render(f"{folder}/ic_launcher.png", size)
            render(f"{folder}/ic_launcher_round.png", size)
            render(f"{folder}/ic_launcher_foreground.png", size * 9 // 4)
            stat = ROOT / folder / "ic_stat_logo.png"
            subprocess.run([magick, "-background", "none", str(source), "-resize",
                            f"{size // 2}x{size // 2}!", "-channel", "RGB", "-evaluate", "set",
                            "100%", "+channel", "-strip", f"PNG32:{stat}"], check=True)

        tmp_ico = Path(temp) / "brand.ico"
        subprocess.run([magick, "-background", "none", str(source), "-define",
                        "icon:auto-resize=256,128,64,48,32,24,16", str(tmp_ico)], check=True)
        for path in ("res/icon.ico", "res/tray-icon.ico", "flutter/windows/runner/resources/app_icon.ico"):
            shutil.copyfile(tmp_ico, ROOT / path)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--license-api", help="Override the API for a local test build")
    args = parser.parse_args()
    apply(json.loads((ROOT / "branding.json").read_text(encoding="utf-8")), args.license_api)
